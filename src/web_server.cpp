static void handleCameraPost() {
    String body = _server.arg("plain");
    if (!requireSaneBody(body)) return;

    if (jsonHas(body, "scan")) {
        // {"scan": true} — user-initiated discovery scan.
        // Refuse to start a second scan while one is in progress so the
        // 5 s window is not split across two competing jobs on the radio.
        if (scanResultsIsScanning()) {
            // Graceful degradation: tell the UI we are already scanning,
            // don't throw 400.
            _server.send(200, "application/json", "{\"ok\":true,\"already\":true}");
            return;
        }
        // Server-side throttle: block scripted scan floods that would hog
        // the single 2.4 GHz radio (BLE scan duty + SoftAP beacons).
        uint32_t now = millis();
        if (_lastScanStartMs != 0 && now - _lastScanStartMs < WEB_SCAN_COOLDOWN_MS) {
            _server.send(429, "application/json",
                         "{\"ok\":false,\"error\":\"scan cooldown, try again shortly\"}");
            return;
        }
        _lastScanStartMs = now;
        camStartUserScan();
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (jsonHas(body, "select")) {
        long idx = jsonGetNum(body, "select", -1);
        if (idx < 0 || !camRegistrySelect((uint8_t)idx)) {
            sendJsonError("invalid camera index");
            return;
        }
        camKick();   // Stop scanning, connect to the selected MAC right away
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (jsonHas(body, "remove")) {
        long idx = jsonGetNum(body, "remove", -1);
        if (idx < 0 || !camRegistryRemove((uint8_t)idx)) {
            sendJsonError("invalid camera index");
            return;
        }
        // Also disconnect BLE if removing the active camera
        camDisconnect();
        _server.send(200, "application/json", "{\"ok\":true}");
    } else if (jsonHas(body, "pair")) {
        // "pair" body: {"mac":"AA:BB:...","type":0|1}
        String mac = jsonGetStr(body, "mac");
        long type = jsonGetNum(body, "type", -1);
        
        // Security: Validate MAC format strictly (17 chars, XX:XX:XX:XX:XX:XX)
        if (mac.length() != 17) {
            sendJsonError("pair: invalid MAC length");
            return;
        }
        for (int i = 0; i < 17; i++) {
            char c = mac.charAt(i);
            if (i % 3 == 2) {
                if (c != ':') {
                    sendJsonError("pair: invalid MAC format");
                    return;
                }
            } else {
                if (!isHexadecimalDigit(c)) {
                    sendJsonError("pair: invalid MAC character");
                    return;
                }
            }
        }
        
        if ((type != CAMERA_DJI && type != CAMERA_GOPRO)) {
            sendJsonError("pair: mac and type required");
            return;
        }
        
        // Check if device is currently visible in scan results (online check).
        // Uses the same live scan-results table that /api/scan serves, so a
        // device shown in the Discover card is always pairable.
        ScanResult const *sorted[MAX_SCAN_RESULTS];
        uint8_t scount = scanResultsGetSortedByRssi(sorted, MAX_SCAN_RESULTS);
        bool isOnline = false;
        char nameBuf[24] = "";
        for (uint8_t i = 0; i < scount; i++) {
            if (strcasecmp(sorted[i]->mac, mac.c_str()) == 0 &&
                sorted[i]->type == (uint8_t)type) {
                isOnline = true;
                // Sanitize device name to prevent XSS
                sanitizeDeviceName(nameBuf, sorted[i]->name, sizeof(nameBuf));
                break;
            }
        }
        // Don't allow pairing with offline devices
        if (!isOnline) {
            sendJsonError("Cannot pair: device is offline or not in range");
            return;
        }
        if (!camRegistrySave((uint8_t)type, mac.c_str(),
                              nameBuf[0] ? nameBuf : mac.c_str())) {
            sendJsonError("pair: registry full or invalid");
            return;
        }
        // Find the newly-saved entry's index and select+kick it.
        for (uint8_t i = 0; i < settingsGet().camCount; i++) {
            if (strcasecmp(settingsGet().cams[i].mac, mac.c_str()) == 0 &&
                settingsGet().cams[i].type == (uint8_t)type) {
                camRegistrySelect(i);
                camKick();
                break;
            }
        }
        _server.send(200, "application/json", "{\"ok\":true}");
    } else {
        sendJsonError("expected scan, select, remove, or pair");
    }
}

// MSP passthrough — lets the Web UI talk MSP directly to the FC.
// Read-only allowlist: safe introspection commands only.  This is the
// foundation for a future browser-side "configurator-lite" panel.
//
// PRIVACY NOTE: MSP_RAW_GPS (108) is deliberately NOT exposed — GPS/position
// over unauthenticated Wi-Fi is a tracking risk. Altitude (109) stays because
// the Dashboard MSP console offers it and it carries no position fix.
// ──────────────────────────────────────────────────────────────────────────────

// Named MSP codes used by the allowlist (see msp_protocol.h for the rest).
static const uint16_t kMspBuildInfo    = 5;
static const uint16_t kMspMotor        = 104;
static const uint16_t kMspAltitude     = 109;
static const uint16_t kMspBoxNames     = 116;
static const uint16_t kMspBatteryState = 130;

static bool mspCmdAllowed(uint16_t cmd) {
    static const uint16_t kAllowed[] = {
        MSP_API_VERSION,   // 1
        MSP_FC_VARIANT,    // 2
        MSP_FC_VERSION,    // 3
        MSP_BOARD_INFO,    // 4
        kMspBuildInfo,     // 5
        MSP_STATUS,        // 101
        kMspMotor,         // 104
        MSP_RC,            // 105
        kMspAltitude,      // 109 (no GPS: see note above)
        MSP_ANALOG,        // 110
        kMspBoxNames,      // 116
        MSP_BOXIDS,        // 119
        kMspBatteryState,  // 130
    };
    for (size_t i = 0; i < sizeof(kAllowed) / sizeof(kAllowed[0]); i++) {
        if (kAllowed[i] == cmd) return true;
    }
    return false;
}

static void handleMspPost() {
    String body = _server.arg("plain");
    if (!requireSaneBody(body)) return;
    long cmd = jsonGetNum(body, "cmd", -1);

    if (cmd < 0 || cmd > 255) {
        sendJsonError("missing/invalid cmd");
        return;
    }
    if (!mspCmdAllowed((uint16_t)cmd)) {
        sendJsonError("command not in read-only allowlist");
        return;
    }

    // Flush any stale bytes, then send the request and wait for the reply.
    // Safe here: we run inside loop()'s call stack (single-threaded), and the
    // main-loop parser simply resyncs on '$' afterwards.
    while (Serial1.available()) Serial1.read();

    mspSendRequest((uint8_t)cmd);

    MspMessage msg;
    uint32_t started = millis();
    bool got = false;
    while (millis() - started < MSP_RESPONSE_TIMEOUT_MS) {
        while (Serial1.available()) {
            uint8_t b = Serial1.read();
            if (mspParseByte(b, msg)) {
                fcStatusFeed(msg);          // Keep live stats fresh
                if ((uint16_t)msg.cmd == (uint16_t)cmd && msg.valid && !msg.isError) {
                    got = true;
                    break;
                }
            }
        }
        if (got) break;
        delay(2);
        yield();
    }

    if (!got) {
        _server.send(504, "application/json",
                     "{\"ok\":false,\"error\":\"FC timeout\"}");
        return;
    }

    // Hex-encode the payload.
    static char hex[MSP_MAX_PAYLOAD_SIZE * 3 + 4];
    size_t o = 0;
    for (uint8_t i = 0; i < msg.payloadSize; i++) {
        o += snprintf(hex + o, sizeof(hex) - o, "%02X", msg.payload[i]);
    }
    hex[o] = '\0';

    char out[192];
    snprintf(out, sizeof(out),
             "{\"ok\":true,\"cmd\":%u,\"len\":%u,\"payload\":\"%s\"}",
             (unsigned)msg.cmd, (unsigned)msg.payloadSize, hex);
    _server.send(200, "application/json", out);
}

// ──────────────────────────────────────────────────────────────────────────────
// Scan Results Endpoint
// ──────────────────────────────────────────────────────────────────────────────

static void handleScanResults() {
    // Serve the REAL scan-results table (populated directly by the BLE
    // scan callbacks, sorted strongest-RSSI first) — not the cam_registry
    // discovered list, which is fed through a single-slot "newest wins"
    // funnel and drops all but the last advertiser.
    ScanResult const *sorted[MAX_SCAN_RESULTS];
    uint8_t n = scanResultsGetSortedByRssi(sorted, MAX_SCAN_RESULTS);

    static char buf[4096];
    char *p = buf;
    size_t left = sizeof(buf);

    size_t w = snprintf(p, left, "{\"scanning\":%s,\"results\":[",
                        scanResultsIsScanning() ? "true" : "false");
    p += w; left -= w;

    // Field names match what the Web UI's renderDiscovered() reads:
    // r.mac, r.n (name), r.t (type STRING 'GoPro'/'DJI'), r.rssi.
    for (uint8_t i = 0; i < n && left > 96; i++) {
        if (i > 0) { *p++ = ','; left--; }

        // Sanitize device name before sending to client (prevent XSS)
        char sanitizedName[24] = "";
        sanitizeDeviceName(sanitizedName, sorted[i]->name, sizeof(sanitizedName));

        const char *typeStr = (sorted[i]->type == CAMERA_GOPRO) ? "GoPro" : "DJI";
        w = snprintf(p, left,
                     "{\"mac\":\"%s\",\"n\":\"%s\",\"t\":\"%s\",\"rssi\":%d}",
                     sorted[i]->mac, sanitizedName, typeStr, sorted[i]->rssi);
        p += w; left -= w;
    }

    // Close the array and the object — without this the JSON is invalid,
    // r.json() throws in the browser, and the Discover card stays empty.
    if (left > 2) { snprintf(p, left, "]}"); }
    else { snprintf(buf, sizeof(buf), "{\"scanning\":false,\"results\":[]}"); }

    _server.sendHeader("Cache-Control", "no-store");
    _server.sendHeader("X-Content-Type-Options", "nosniff");
    _server.send(200, "application/json", buf);
}

// ──────────────────────────────────────────────────────────────────────────────
// OTA Firmware Update Endpoint
// ──────────────────────────────────────────────────────────────────────────────
// Correct ESP32 WebServer pattern: one UPLOAD callback streams the bytes,
// one RESPONSE callback sends the single final JSON. Never send() from
// inside UPLOAD_FILE_START/WRITE — it corrupts the upload connection.
//
// SECURITY STATUS (be honest): this endpoint has NO auth and NO signature
// check — anyone joined to the AP can flash firmware. Mitigations in place:
//   • size cap (rejects images larger than free sketch space),
//   • Update.abort() on any error (no wedged half-flash),
//   • single final response (no mid-upload sends).
// Full fix (admin session + ECDSA signature) is roadmap — see README.
// ──────────────────────────────────────────────────────────────────────────────

static void handleOtaUpload() {
    HTTPUpload& upload = _server.upload();

    if (upload.status == UPLOAD_FILE_START) {
        _otaActive = true;
        _otaOk = false;
        _otaError[0] = '\0';
        _otaBytes = 0;
        _otaMaxBytes = ESP.getFreeSketchSpace();
        Serial.printf("OTA Start: %s\n", upload.filename.c_str());

        if (_otaMaxBytes == 0) {
            snprintf(_otaError, sizeof(_otaError), "no space for update");
            Update.abort();
            _otaActive = false;
            return;
        }
        if (!Update.begin(UPDATE_SIZE_UNKNOWN)) {
            snprintf(_otaError, sizeof(_otaError), "Begin failed");
            Serial.printf("OTA Begin Error: %s\n", Update.errorString());
            Update.abort();
            _otaActive = false;
        }
    } else if (upload.status == UPLOAD_FILE_WRITE) {
        if (!_otaActive) return;  // begin already failed — drain silently
        // Incremental size cap: never write past free sketch space.
        if (_otaBytes + upload.currentSize > _otaMaxBytes) {
            snprintf(_otaError, sizeof(_otaError), "image too large");
            Update.abort();
            _otaActive = false;
            return;
        }
        if (Update.write(upload.buf, upload.currentSize) != upload.currentSize) {
            snprintf(_otaError, sizeof(_otaError), "Write failed");
            Serial.printf("OTA Write Error: %s\n", Update.errorString());
            Update.abort();
            _otaActive = false;
        } else {
            _otaBytes += upload.currentSize;
        }
    } else if (upload.status == UPLOAD_FILE_END) {
        if (_otaActive && Update.end(true)) {
            Serial.printf("OTA Success: %u bytes written\n", upload.totalSize);
            _otaOk = true;
        } else {
            if (!_otaError[0]) snprintf(_otaError, sizeof(_otaError), "End failed");
            Serial.printf("OTA End Error: %s\n", Update.errorString());
            Update.abort();
            _otaActive = false;
        }
    } else if (upload.status == UPLOAD_FILE_ABORTED) {
        Update.abort();
        _otaActive = false;
        snprintf(_otaError, sizeof(_otaError), "upload aborted");
    }
}

static void handleOtaResponse() {
    _server.sendHeader("Connection", "close");
    if (_otaOk) {
        _otaOk = false;
        _server.send(200, "application/json",
            "{\"ok\":true,\"message\":\"Firmware updated! Rebooting...\"}");
        delay(200);
        ESP.restart();
    } else {
        char out[160];
        snprintf(out, sizeof(out), "{\"ok\":false,\"error\":\"%s\"}",
                 _otaError[0] ? _otaError : "update failed");
        _otaError[0] = '\0';
        _server.send(500, "application/json", out);
    }
}

static void handleOtaStatus() {
    char out[128];
    snprintf(out, sizeof(out), 
        "{\"ok\":true,\"version\":\"%s\",\"free_heap\":%lu}",
        FIRMWARE_VERSION, (unsigned long)ESP.getFreeHeap());
    _server.send(200, "application/json", out);
}

static void redirectToRoot() {
    String uri = _server.uri();
    // API paths must fail closed with JSON (not a 302 to HTML) so wrong-method
    // probes and scripts can't be hidden behind the captive-portal redirect.
    if (uri.startsWith("/api/")) {
        _server.send(404, "application/json",
                     "{\"ok\":false,\"error\":\"not found\"}");
        return;
    }
    _server.sendHeader(String("Location"), String("http://") + _ipStr + "/", true);
    _server.send(302, "text/plain", "");
}

// ── OS captive-portal probe handlers ─────────────────────────────────────────
// Each OS probes a known URL to detect "internet available".  Answering these
// with their expected SUCCESS bodies makes Windows/iOS/Android mark the
// network as usable immediately — no scary errors, no blocked popups.  Any
// other hostname still lands on our UI via the onNotFound redirect.

static const char NCSI_SUCCESS[] =
    "Microsoft Connect Test";

static void handleProbeConnectTest() {          // Windows: /connecttest.txt
    _server.send(200, "text/plain", NCSI_SUCCESS);
}

static void handleProbeNcsi() {                 // Windows legacy: /ncsi.txt
    _server.send(200, "text/plain", "Microsoft NCSI");
}

static void handleProbe204() {                  // Android: /generate_204
    _server.send(204, "text/plain", "");
}

static void handleProbeApple() {                // iOS/macOS: /hotspot-detect.html
    _server.send(200, "text/html",
                 "<HTML><HEAD><TITLE>Success</TITLE></HEAD><BODY>Success</BODY></HTML>");
}

// ──────────────────────────────────────────────────────────────────────────────
// Lifecycle
// ──────────────────────────────────────────────────────────────────────────────

void webStart() {
    const ShutterSettings &cfg = settingsGet();
    if (_up) return;   // Already running

    WiFi.persistent(false);              // Keep Wi-Fi creds out of NVS
    WiFi.mode(WIFI_AP);
    delay(50);

    // Deterministic AP address: 192.168.4.1/24 (matches UI + captive portal).
    IPAddress localIp(192, 168, 4, 1);
    IPAddress gateway(192, 168, 4, 1);
    IPAddress subnet(255, 255, 255, 0);
    WiFi.softAPConfig(localIp, gateway, subnet);

    // WPA2 needs 8..63 chars. Shorter stored passwords (e.g. legacy open or
    // truncated entries) fall back to OPEN with a loud log — the POST path
    // already rejects new weak passwords (see handleSettingsPost).
    size_t passLen = strlen(cfg.apPass);
    bool havePass = (passLen >= WIFI_AP_PASS_MIN_LEN &&
                     passLen <= WIFI_AP_PASS_MAX_LEN);
    bool ok;
    if (havePass) {
        ok = WiFi.softAP(cfg.apSsid, cfg.apPass);
    } else {
        ok = WiFi.softAP(cfg.apSsid);   // Open network
    }
    if (!ok) {
        DBG("WEB: SoftAP failed — retrying once");
        delay(200);
        ok = havePass ? WiFi.softAP(cfg.apSsid, cfg.apPass)
                      : WiFi.softAP(cfg.apSsid);
    }
    if (!ok) {
        DBG("WEB: SoftAP failed twice!");
        _up = false;
        return;
    }

    strlcpy(_ipStr, localIp.toString().c_str(), sizeof(_ipStr));

    // Captive DNS: every hostname resolves to us.
    _dns.stop();
    _dns.setErrorReplyCode(DNSReplyCode::NoError);
    if (!_dns.start(53, "*", localIp)) {
        DBG("WEB: captive DNS failed to start");
    }

    _server.stop();
    _server.on("/",               HTTP_GET,  handleRoot);
    _server.on("/api/status",     HTTP_GET,  handleStatus);
    _server.on("/api/settings",   HTTP_POST, handleSettingsPost);
    _server.on("/api/camera",     HTTP_POST, handleCameraPost);
    _server.on("/api/command",    HTTP_POST, handleCommand);
    _server.on("/api/msp",        HTTP_POST, handleMspPost);
    _server.on("/api/scan",       HTTP_GET,  handleScanResults);
    // OTA needs the two-callback form: response fn + upload-streaming fn.
    _server.on("/api/ota", HTTP_POST, handleOtaResponse, handleOtaUpload);
    _server.on("/api/ota/status", HTTP_GET,  handleOtaStatus);

    // OS connectivity probes → answer with SUCCESS bodies (see handlers above).
    _server.on("/connecttest.txt",              HTTP_GET, handleProbeConnectTest);
    _server.on("/ncsi.txt",                     HTTP_GET, handleProbeNcsi);
    _server.on("/generate_204",                 HTTP_GET, handleProbe204);
    _server.on("/gen_204",                      HTTP_GET, handleProbe204);
    _server.on("/hotspot-detect.html",          HTTP_GET, handleProbeApple);
    _server.on("/library/test/success.html",    HTTP_GET, handleProbeApple);
    // Anything else (any hostname, any path) → our UI.
    _server.onNotFound(redirectToRoot);

    _server.begin();
    _up = true;

    DBG("WEB: AP '%s' up — http://%s/ (open=%s)",
        cfg.apSsid, _ipStr, havePass ? "false" : "true");
}

void webStop() {
    if (!_up) return;
    _dns.stop();
    _server.stop();
    WiFi.softAPdisconnect(true);
    WiFi.mode(WIFI_OFF);          // Powers down the Wi-Fi radio (BLE unaffected)
    _up = false;
    DBG("WEB: Wi-Fi powered off (radio switch)");
}

void webInit() {
    // Boot-time entry point.  Always starts the AP so the user can never be
    // locked out; a configured radio switch turns it off once RC data flows.
    webStart();
}

void webUpdate() {
    if (!_up) return;
    _dns.processNextRequest();
    _server.handleClient();
}


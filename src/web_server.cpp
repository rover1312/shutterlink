// ──────────────────────────────────────────────────────────────────────────────
// Tiny flat-JSON readers (payloads are generated by our own UI, so a simple
// scanner is sufficient and avoids pulling in a JSON library).
//
// LIMITS: every POST body is capped at WEB_MAX_JSON_BODY_LEN (config.h) and
// checked by requireSaneBody() before parsing. Duplicate keys resolve to the
// FIRST occurrence (fail-closed); numbers are clamped to avoid long overflow.
// ──────────────────────────────────────────────────────────────────────────────

/// Reject oversized POST bodies with 413 before any String duplication.
/// Returns true when the body is safe to parse.
static bool requireSaneBody(const String &body) {
    if (body.length() > WEB_MAX_JSON_BODY_LEN) {
        _server.send(413, "application/json",
                     "{\"ok\":false,\"error\":\"body too large\"}");
        return false;
    }
    return true;
}

static int jsonKeyIndex(const String &body, const char *key) {
    // Match "key" exactly (surrounded by quotes).
    String pat = "\"";
    pat += key;
    pat += "\"";
    return body.indexOf(pat);
}

static bool jsonHas(const String &body, const char *key) {
    return jsonKeyIndex(body, key) >= 0;
}

static long jsonGetNum(const String &body, const char *key, long def = 0) {
    int i = jsonKeyIndex(body, key);
    if (i < 0) return def;
    i = body.indexOf(':', i);
    if (i < 0) return def;
    i++;
    while (i < (int)body.length() && isspace((unsigned char)body[i])) i++;
    if (i >= (int)body.length()) return def;
    bool neg = false;
    if (body[i] == '-') { neg = true; i++; }
    if (i >= (int)body.length() || !isdigit((unsigned char)body[i])) return def;
    long val = 0;
    while (i < (int)body.length() && isdigit((unsigned char)body[i])) {
        int digit = body[i] - '0';
        // Clamp on overflow instead of wrapping (fail-closed for thresholds).
        if (val > (LONG_MAX - digit) / 10) {
            return neg ? LONG_MIN : LONG_MAX;
        }
        val = val * 10 + digit;
        i++;
    }
    return neg ? -val : val;
}

static bool jsonGetBool(const String &body, const char *key, bool def = false) {
    int i = jsonKeyIndex(body, key);
    if (i < 0) return def;
    i = body.indexOf(':', i);
    if (i < 0) return def;
    // Look at the raw characters following the colon.
    int j = i + 1;
    while (j < (int)body.length() && isspace((unsigned char)body[j])) j++;
    if (body.startsWith("true", j))  return true;
    if (body.startsWith("false", j)) return false;
    return jsonGetNum(body, key, def ? 1 : 0) != 0;
}

static String jsonGetStr(const String &body, const char *key) {
    int i = jsonKeyIndex(body, key);
    if (i < 0) return "";
    i = body.indexOf(':', i);
    if (i < 0) return "";
    i = body.indexOf('"', i);          // opening quote of value
    if (i < 0) return "";
    // Find the closing quote, honouring backslash escapes (\").
    String out;
    out.reserve(32);
    for (int j = i + 1; j < (int)body.length(); j++) {
        char c = body[j];
        if (c == '\\' && j + 1 < (int)body.length()) {
            // Keep the escaped char literally (\" -> ", \\ -> \).
            out += body[++j];
        } else if (c == '"') {
            return out;
        } else {
            out += c;
        }
        if (out.length() > 64) break;  // values we care about are short
    }
    return "";  // unterminated — treat as missing
}

